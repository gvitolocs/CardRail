// eslint-disable-next-line no-unused-expressions -- Playwright CLI evaluates this callback.
async page => {
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.setViewportSize({width:1920,height:1080});
  await page.getByRole('heading',{name:'Scan cards',exact:true}).waitFor();
  await page.getByRole('link',{name:'Open on phone',exact:true}).waitFor({timeout:30000});
  await page.screenshot({path:'/home/nez/Projects/CardRail/docs/reference-empty-desktop.png',fullPage:true});
  const pairingUrl=await page.getByRole('link',{name:'Open on phone'}).getAttribute('href');
  const phoneContext=await page.context().browser().newContext({viewport:{width:390,height:844}}), phone=await phoneContext.newPage();
  const code=(await page.getByLabel('Pairing code',{exact:true}).locator('span').allTextContents()).join('');
  const phoneUrl=await page.evaluate(()=>location.origin+'/connect');
  await phone.goto(phoneUrl);
  await phone.getByLabel('Desktop pairing code',{exact:true}).fill(code);
  await phone.getByRole('button',{name:'Connect phone',exact:true}).click();
  await page.getByRole('button',{name:'Allow phone',exact:true}).waitFor({timeout:15000});
  const requested=await page.evaluate(async()=>await(await fetch('/api/v1/inventory')).json());
  const unauthorized=await phone.evaluate(async id=>(await fetch('/api/v1/capture',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({action:'approve-code',id})})).status,requested.scanPairRequest.id);
  if(unauthorized===200)throw new Error('Phone approved its own access');
  await page.getByRole('button',{name:'Allow phone',exact:true}).click();
  await phone.getByRole('heading',{name:'Connected to your desk',exact:true}).waitFor({timeout:30000});
  const reuse=await phone.evaluate(async url=>{const q=new URLSearchParams(new URL(url).hash.slice(1));return(await fetch('/api/v1/capture',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({action:'pair',id:q.get('capture'),secret:q.get('key'),code:q.get('code')})})).status;},pairingUrl);
  if(reuse===200)throw new Error('Approved code left the QR reusable');

  await page.getByRole('heading',{name:'Phone connected',exact:true}).waitFor({timeout:15000});
  await page.getByRole('group',{name:'Batch condition',exact:true}).getByRole('button',{name:'SP',exact:true}).click();
  await page.getByRole('group',{name:'Batch flags',exact:true}).getByRole('button',{name:'Signed',exact:true}).click();
  await page.getByLabel('Batch location',{exact:true}).fill('megaevoluzionietb');
  await page.getByLabel('Batch location',{exact:true}).press('Enter');
  await page.getByRole('button',{name:'Stack setup',exact:true}).click();
  await page.getByLabel('Cards per stack',{exact:true}).fill('2');
  await page.getByLabel('Cards per stack',{exact:true}).press('Tab');
  await page.getByRole('button',{name:'Done',exact:true}).click();
  await page.getByLabel('Add card search',{exact:true}).fill('Bulbasaur');
  await page.getByRole('listbox',{name:'Catalog results'}).getByRole('option').first().waitFor({timeout:20000});
  await page.getByRole('listbox',{name:'Catalog results'}).getByRole('option').first().click();
  await page.getByLabel('New card quantity',{exact:true}).fill('2');
  await page.getByLabel('New card price',{exact:true}).fill('5');
  await page.getByRole('button',{name:'Add to queue',exact:true}).click();
  await page.getByLabel('Quantity 1',{exact:true}).waitFor();
  if(await page.getByLabel('Quantity 1',{exact:true}).inputValue()!=='2')throw new Error('Manual quantity lost');
  await page.getByLabel('Add card search',{exact:true}).fill('Bulbasaur');
  await page.getByRole('listbox',{name:'Catalog results'}).getByRole('option').first().waitFor({timeout:20000});
  await page.getByRole('listbox',{name:'Catalog results'}).getByRole('option').first().click();
  await page.getByRole('button',{name:'Add to queue',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[aria-label="Quantity 1"]')?.value==='3');
  const staged=await page.evaluate(async()=>await(await fetch('/api/v1/inventory')).json());
  if(staged.scanQueue.length!==1 || !staged.scanQueue[0].signed || staged.scanQueue[0].condition!=='SP')throw new Error('Merge or batch defaults failed');
  const name=staged.scanQueue[0].identity.name;
  await page.getByRole('button',{name:'Remove '+name,exact:true}).click();
  await page.getByRole('button',{name:'Undo',exact:true}).click();
  await page.getByLabel('Quantity 1',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Add to collection',exact:true}).click();
  if(await page.getByRole('columnheader',{name:'Price €',exact:true}).count())throw new Error('Collection still shows sale price');
  await page.getByRole('button',{name:'Add 3 cards to collection',exact:true}).click();
  await page.getByText('Cards added to your collection.',{exact:true}).waitFor();
  const collection=await page.evaluate(async()=>await(await fetch('/api/v1/inventory')).json());
  const item=collection.items.find(row=>row.id===staged.scanQueue[0].id);
  if(item.purpose!=='collection' || item.price!==0 || item.location.box!=='megaevoluzionietb' || item.location.end!==3)throw new Error('Collection or stack allocation incorrect');
  await page.getByRole('button',{name:'My Card Rails',exact:true}).click();
  await page.getByRole('button',{name:'Collection',exact:true}).click();
  await page.getByRole('button',{name:'Open card',exact:true}).last().click();
  if(await page.getByRole('button',{name:'Record sale',exact:true}).count())throw new Error('Collection offered for sale');
  await page.getByRole('button',{name:'Close ×',exact:true}).click();
  await page.getByRole('button',{name:'Scan Pokémon',exact:true}).click();
  await page.getByRole('button',{name:'List for sale',exact:true}).click();
  await phone.locator('input[type=file]').setInputFiles('/home/nez/Projects/CardRail/public/cards/bulbasaur.png');
  await phone.getByText('Bulbasaur added to the queue.',{exact:true}).waitFor({timeout:60000});
  await page.getByRole('button',{name:/Bulbasaur.*MEP/}).waitFor({timeout:15000});
  await page.getByLabel('Quantity 1',{exact:true}).fill('5');
  await page.getByLabel('Price 1',{exact:true}).fill('12');
  await page.getByLabel('Finish 1',{exact:true}).selectOption('Holo');
  await page.evaluate(async()=>{await Promise.all([...document.querySelectorAll('.pokemon-table img')].map(img=>img.decode().catch(()=>{})))});
  await page.screenshot({path:'/home/nez/Projects/CardRail/docs/reference-filled-desktop.png',fullPage:true});
  await phone.evaluate(async()=>{await Promise.all([...document.querySelectorAll('.pokemon-table img')].map(img=>img.decode().catch(()=>{})))});
  await phone.screenshot({path:'/home/nez/Projects/CardRail/docs/reference-phone.png',fullPage:true});
  await page.getByRole('button',{name:'Add 5 cards to inventory',exact:true}).click();
  await page.getByText('Cards added to inventory. Continue scanning or open Inventory to list them.',{exact:true}).waitFor();
  const after=await page.evaluate(async()=>await(await fetch('/api/v1/inventory')).json());
  const scanned=after.items.find(item=>item.source==='scan' && item.identity.name==='Bulbasaur');
  if(scanned.quantity!==5 || scanned.price!==12 || scanned.printing!=='Holo' || scanned.location.position!==4 || scanned.location.end!==8)throw new Error('Scan row edits or positions lost');
  await page.reload();await page.getByRole('heading',{name:'Scan cards',exact:true}).waitFor();
  const reloaded=await page.evaluate(async()=>await(await fetch('/api/v1/inventory')).json());
  if(reloaded.items.length!==after.items.length || reloaded.scanSettings.stackSize!==2)throw new Error('Reload lost settings or inventory');
  await phoneContext.close();if(errors.length)throw new Error(errors.join('; '));
  return {autoQR:true,manualCodeApproval:true,sharedPhone:true,publicCatalog:true,mergeRepeats:true,flags:true,stackAllocation:true,undo:true,collectionSeparate:true,liveRecognition:true,scanToInventory:true,reload:true,consoleErrors:0};
}
