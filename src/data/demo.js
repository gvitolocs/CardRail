export function resolveScan(raw, items) {
  const already = items.find(
    (entry) =>
      entry.source === 'scan' &&
      entry.identity.name === raw.name &&
      entry.identity.number === raw.number,
  )
  if (already) return null

  const intake = items.filter((entry) => entry.location.box === '05')
  const position = 2100 + intake.length
  const row = String(1 + Math.floor(intake.length / 4))

  return {
    id: `cr_${position}`,
    identity: {
      game: raw.game,
      name: raw.name,
      setName: raw.setName,
      number: raw.number,
    },
    language: raw.language,
    condition: raw.condition,
    printing: raw.printing,
    quantity: 1,
    price: raw.price,
    currency: 'EUR',
    location: { box: '05', row, position },
    listings: [],
    source: 'scan',
  }
}

