function item(card) {
  return {
    id: `cr_${card.position}`,
    identity: {
      game: card.game,
      name: card.name,
      setName: card.setName,
      number: card.number,
    },
    language: card.language,
    condition: card.condition,
    printing: card.printing,
    quantity: 1,
    price: card.price,
    currency: 'EUR',
    location: { box: card.box, row: card.row, position: card.position },
    listings: (card.listings || []).map(([platform, externalId]) => ({
      platform,
      externalId,
      quantity: 1,
      price: card.price,
    })),
    source: 'import',
    art: card.art,
    chip: card.chip,
    flag: card.flag,
    gameIcon: card.gameIcon,
  }
}

